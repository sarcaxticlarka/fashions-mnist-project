"""Writes report/p2_numbers.tex: LaTeX macros for every final-model number used in
report/phase2_full_report.tex, so the PDF always matches results/tables.

    python scripts/11_report_numbers.py && (cd report && tectonic phase2_full_report.tex)
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import pandas as pd
from src.config import TABLE_DIR, ROOT

fs = json.loads((TABLE_DIR / "p2_final_summary.json").read_text())
pr = pd.read_csv(TABLE_DIR / "p2_final_per_run.csv")
seed = pd.read_csv(TABLE_DIR / "p2_final_seed_summary.csv").set_index("family")


def pct(v, d=2):
    return f"{v*100:.{d}f}\\%"


def sci(p):
    m, e = f"{p:.1e}".split("e")
    return f"${m}\\times10^{{{int(e)}}}$"


best = pr.sort_values("val_acc", ascending=False).iloc[0]
def fam(f, col):
    return seed.loc[f, col] if f in seed.index else float("nan")

M = {
    "FinalAcc": pct(fs["test_acc"]), "FinalFone": f"{fs['test_macro_f1']:.4f}", "FinalErr": f"{fs['errors']}",
    "FinalErrDrop": f"{870 - fs['errors']}", "FinalGain": f"{(fs['test_acc'] - 0.913) * 100:+.2f}",
    "FinalCIlo": pct(fs["ci"][0]), "FinalCIhi": pct(fs["ci"][1]), "FinalShirt": pct(fs["per_class_recall"]["Shirt"], 1),
    "FinalTshirt": pct(fs["per_class_recall"]["T-shirt/top"], 1),
    "FinalPullover": pct(fs["per_class_recall"]["Pullover"], 1), "FinalCoat": pct(fs["per_class_recall"]["Coat"], 1),
    "FinalMembers": f"{len(fs['members'])}", "FinalName": fs["final_model"].replace("_", "\\_"),
    "FinalParams": f"{fs['params']:,}".replace(",", "{,}"), "FinalMs": f"{fs['ms_per_image']:.1f}",
    "FinalPreBias": pct(fs["test_acc_before_bias"]), "Temp": f"{fs['temperature']:.2f}", "ShirtBias": f"{fs['shirt_bias']:.2f}",
    "EceBefore": pct(fs["ece_before"]), "EceAfter": pct(fs["ece_after"]),
    "AbsThr": f"{fs['abstain']['threshold']*100:.0f}\\%", "AbsCov": pct(fs["abstain"]["test_coverage"], 1),
    "AbsAcc": pct(fs["abstain"]["test_acc_on_kept"]), "AbsShirt": pct(fs["abstain"]["shirt_share_of_abstained"], 0),
    "PvsSVM": sci(fs["mcnemar_vs_svm"]["p"]), "PvsGAP": sci(fs["mcnemar_vs_gap"]["p"]),
    "ChiSVM": f"{fs['mcnemar_vs_svm']['chi2']:.1f}", "ChiGAP": f"{fs['mcnemar_vs_gap']['chi2']:.1f}",
    "BestSingle": best.run.replace("_", "\\_"), "BestSingleAcc": pct(best.test_acc), "BestSingleTTA": pct(best.test_acc_tta),
    "GapFortyMean": pct(fam("CNN3Block_GAP_E40", "test_mean")), "GapFortyStd": f"{fam('CNN3Block_GAP_E40', 'test_std')*100:.2f}",
    "ResMean": pct(fam("ResNetSmall", "test_mean")), "ResStd": f"{fam('ResNetSmall', 'test_std')*100:.2f}",
    "ResShirt": pct(fam("ResNetSmall", "shirt_mean"), 1), "GapFortyShirt": pct(fam("CNN3Block_GAP_E40", "shirt_mean"), 1),
    "NSeeds": f"{int(seed['n_seeds'].min())}",
}
lines = ["% auto-generated by scripts/11_report_numbers.py - do not edit"]
lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in M.items()]
(ROOT / "report" / "p2_numbers.tex").write_text("\n".join(lines) + "\n")
print("\n".join(lines))
